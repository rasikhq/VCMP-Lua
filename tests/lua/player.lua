-- Player (bindings/player.cpp) against the recording fake server.

local p = fake.connect("Alice")

test("class basics", function()
    expect_eq(Player.type(), "Player", "Player.type()")
    expect_eq(p:getType(), "Player", "getType")
    expect_eq(p.id, 0, "id")
    expect_eq(p:getID(), 0, "getID")
    expect_eq(p.valid, true, "valid")
    expect_eq(Player.findByID(0), p, "findByID")
    expect_eq(Player.findByID(99), nil, "findByID of a free id")
    expect_eq(Player.findByID(-1), nil, "findByID(-1)")
    expect_eq(Player.count(), 1, "count")
    expect_eq(tostring(p), "Player(0)", "tostring")
end)

test("messages are sent with a %s format", function()
    expect_eq(p:msg("hello %n %s"), true, "msg")
    expect_call('SendClientMessage(0, 4294967295, "hello %n %s")')
    p:msg("red", 0xFF0000FF)
    expect_call('SendClientMessage(0, 4278190335, "red")')
    p:msg("negative colour", -1)
    expect_call('SendClientMessage(0, 4294967295, "negative colour")')
    p:announce("big", 3)
    expect_call('SendGameMessage(0, 3, "big")')
    p:announce("default type")
    expect_call('SendGameMessage(0, 0, "default type")')
end)

