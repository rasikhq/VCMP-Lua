test("vehicle and spectateTarget accept nil", function()
    expect_eq(p.vehicle, nil, "not in a vehicle")
    fake.clear()
    p.vehicle = nil
    expect_calls({ "GetPlayerVehicleId(0)" })
    local vehicle = test_create_vehicle()
    fake.ret("GetPlayerVehicleId", vehicle.id)
    expect_eq(p.vehicle, vehicle, "the vehicle's handle")
    p.vehicle = nil
    expect_call("RemovePlayerFromVehicle(0)")
    p.vehicle = vehicle
    expect_call("PutPlayerInVehicle(0, " .. vehicle.id .. ", 0, 1, 1)")
    expect_error("bad value for 'vehicle' (Vehicle expected, got Player)", function() p.vehicle = p end)
    fake.ret("GetPlayerVehicleId", 0)

    local q = fake.connect("Carol")
    p.spectateTarget = q
    expect_call("SetPlayerSpectateTarget(0, " .. q.id .. ")")
    p.spectateTarget = nil
    expect_call("SetPlayerSpectateTarget(0, -1)")
    fake.ret("GetPlayerSpectateTarget", -1)
    expect_eq(p.spectateTarget, nil, "no target")
    fake.ret("GetPlayerSpectateTarget", q.id)
    expect_eq(p.spectateTarget, q, "target")
    fake.disconnect(q.id)
end)

