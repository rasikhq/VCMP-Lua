test("static functions", function()
    local q = fake.connect("Eve")
    Player.msgAll("hi all")
    expect_calls({ 'SendClientMessage(0, 4294967295, "hi all")',
                   'SendClientMessage(' .. q.id .. ', 4294967295, "hi all")' })
    fake.clear()
    Player.announceAll("big", 1)
    expect_eq(#fake.calls(), 2, "one announcement per player")
    fake.ret("IsPlayerSpawned", 0)
    expect_eq(next(Player.getActive(true)), nil, "nobody spawned")
    local all = Player.getActive()
    expect_eq(all[0], p, "getActive()[0]")
    expect_eq(all[q.id], q, "getActive()[q.id]")
    fake.ret("IsPlayerSpawned", 1)
    expect_eq(Player.getActive(true)[q.id], q, "getActive(true)")
    fake.ret("GetPlayerIdFromName", q.id)
    expect_eq(Player.findByName("Eve"), q, "findByName")
    fake.ret("GetPlayerIdFromName", -1)
    expect_eq(Player.findByName("nobody"), nil, "findByName of nobody")
    fake.disconnect(q.id)
end)

test("kick: the disconnect happens inside the call and the handle dies", function()
    local q = fake.connect("Mallory")
    local reason
    Event.bind("onPlayerDisconnect", function(player, r)
        if player == q then reason = r end
    end)
    q:kick()
    expect_eq(reason, DisconnectReason.kick, "disconnect reason")
    expect_eq(q.valid, false, "valid after kick")
    expect_error("player no longer exists", function() return q.health end)
    expect_eq(tostring(q), "Player(1, no longer exists)", "tostring")
end)
