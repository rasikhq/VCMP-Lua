test("bad values raise errors that name the property or method", function()
    expect_error("player.lua:", function() p.health = "full" end)
    expect_error("bad value for 'health' (number expected, got string)", function() p.health = "full" end)
    expect_error("bad value for 'world' (number has no integer representation)", function() p.world = 1.5 end)
    expect_error("bad value for 'admin' (boolean expected, got number)", function() p.admin = 1 end)
    expect_error("bad argument #1 to 'setWeapon' (integer expected, got string)",
        function() p:setWeapon("m4", 100) end)
    expect_error("bad argument #2 to 'setWeapon' (integer expected, got no value)",
        function() p:setWeapon(26) end)
end)

test("server errors", function()
    fake.error("SetPlayerWorld", 4)
    expect_error("'world' failed: argument out of bounds", function() p.world = -5 end)
    fake.error("SetPlayerWorld", 0)
    fake.error("PutPlayerInVehicle", 8)
    local vehicle = test_create_vehicle()
    expect_eq(p:setVehicle(vehicle), false, "a refused request returns false")
    fake.error("PutPlayerInVehicle", 0)
    expect_eq(p:setVehicle(vehicle, 1), true, "setVehicle")
    expect_call("PutPlayerInVehicle(0, " .. vehicle.id .. ", 1, 1, 1)")
    fake.error("GetPlayerOption", 4)
    expect_error("'getOption' failed: argument out of bounds", function() p:getOption(99) end)
    fake.error("GetPlayerOption", 0)
    fake.remove("KillPlayer")
    expect_error("KillPlayer is not supported by this server version", function() p:kill() end)
end)

